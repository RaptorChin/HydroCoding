# Week 1 / Project 1：Manning 水理計算器 —— 第 1 版（最簡單版）
# 目的：用 Python 一步一步重現「手算」的過程
# 渠道形狀：矩形渠道
# 單位：公制（m、s），Manning 公式係數 k = 1
# =============================================================

# ---------- 1. 輸入條件（就像 Excel 裡填數字的格子） ----------
b = 3.0        # 渠寬 (m)
h = 2.0        # 水深 (m)
n = 0.03       # Manning 粗糙係數（無因次，實際單位 s/m^(1/3)）
slope = 0.001  # 渠底坡度 S（無因次，0.001 = 千分之一）

# ---------- 2. 幾何計算 ----------
A = b * h          # 斷面積 A = 寬 × 深 (m²)
P = b + 2 * h      # 濕周 P = 底寬 + 兩側壁 (m)
R = A / P          # 水力半徑 R = A / P (m)

# ---------- 3. Manning 公式 ----------
# V = (1/n) × R^(2/3) × S^(1/2)
# 在 Python 裡，「次方」寫成 **，例如 R 的 2/3 次方寫成 R ** (2/3)
V = (1 / n) * R ** (2 / 3) * slope ** 0.5   # 平均流速 (m/s)

# ---------- 4. 流量 ----------
Q = A * V          # 流量 Q = A × V (m³/s)

# ---------- 5. 輸出結果 ----------
# f"..." 叫做 f-string，可以把變數直接塞進文字裡
# {A:.2f} 的意思是：把 A 顯示到小數點後 2 位
print("===== Manning 水理計算結果（矩形渠道）=====")
print(f"渠寬 b      = {b:.2f} m")
print(f"水深 h      = {h:.2f} m")
print(f"粗糙係數 n  = {n}")
print(f"坡度 S      = {slope}")
print("-------------------------------------------")
print(f"斷面積 A    = {A:.3f} m²")
print(f"濕周 P      = {P:.3f} m")
print(f"水力半徑 R  = {R:.4f} m")
print(f"平均流速 V  = {V:.4f} m/s")
print(f"流量 Q      = {Q:.3f} m³/s")
