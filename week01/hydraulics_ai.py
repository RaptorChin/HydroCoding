def manning_trap(b, h, n, slope, z=0.0):
    """
    梯形渠道 Manning 流量計算（公制）

    輸入：
        b     渠底寬 (m)
        h     水深 (m)
        n     Manning 粗糙係數
        slope 渠底坡度 S
        z     邊坡比（水平 : 垂直 = z : 1），預設 0，也就是矩形渠道
    輸出：
        Q     流量 (m³/s)

    梯形斷面示意（z = 水平距離 / 垂直高度）：

        \\<-- z·h -->|<----- b ----->|<-- z·h -->/
         \\          |               |          /
          \\         |               |         /   h
           \\________|_______________|________/
    """
    if b <= 0:
        raise ValueError(f"渠底寬 b 必須大於 0，目前輸入 b = {b}")
    if h <= 0:
        raise ValueError(f"水深 h 必須大於 0，目前輸入 h = {h}")
    if n <= 0 or n > 0.5:
        raise ValueError(f"粗糙係數 n 應介於 0～0.5，目前輸入 n = {n}")
    if slope <= 0:
        raise ValueError(f"坡度 slope 必須大於 0，目前輸入 slope = {slope}")
    if z < 0:
        raise ValueError(f"邊坡比 z 不可為負數，目前輸入 z = {z}")

    A = (b + z * h) * h                     # 斷面積
    P = b + 2 * h * (1 + z ** 2) ** 0.5          # 濕周
    R = A / P                               # 水力半徑
    V = (1 / n) * R ** (2 / 3) * slope ** 0.5
    Q = A * V

    return Q
