def manning_rect(b, h, n, slope):
    """
    矩形渠道 Manning 流量計算（公制）

    輸入：
        b     渠寬 (m)，必須 > 0
        h     水深 (m)，必須 > 0
        n     Manning 粗糙係數，必須 > 0
        slope 渠底坡度 S，必須 > 0
    輸出：
        Q     流量 (m³/s)
    """
    # ---------- 輸入檢核：像工地大門的警衛，不合格的不准進去 ----------
    if b <= 0:
        raise ValueError(f"渠寬 b 必須大於 0，目前輸入 b = {b}")
    if h <= 0:
        raise ValueError(f"水深 h 必須大於 0，目前輸入 h = {h}")
    if n <= 0:
        raise ValueError(f"粗糙係數 n 必須大於 0，目前輸入 n = {n}")
    if slope <= 0:
        raise ValueError(f"坡度 slope 必須大於 0，目前輸入 slope = {slope}")

    # ---------- 計算（和第 1 版完全相同） ----------
    A = b * h
    P = b + 2 * h
    R = A / P
    V = (1 / n) * R ** (2 / 3) * slope ** 0.5
    Q = A * V

    return Q   # 把答案交回給呼叫這台機器的人


# =============================================================
# 以下是「使用」這台機器的地方
# =============================================================

# ---------- 測試 1：正常輸入，答案應該和手算的 11.308 一樣 ----------
Q = manning_rect(b=5.0, h=2.0, n=0.03, slope=0.001)
print(f"測試 1（正常輸入）：Q = {Q:.3f} m³/s")

# ---------- 測試 2：故意輸入不合理的數字 ----------
# 每一組是 (b, h, n, slope)
bad_inputs = [
    (5.0, 0.0, 0.03, 0.001),     # h = 0
    (5.0, -1.0, 0.03, 0.001),    # h = -1
    (5.0, 2.0, 0.0, 0.001),      # n = 0
    (5.0, 2.0, 0.03, 0.0),       # slope = 0
]

for b, h, n, slope in bad_inputs:
    try:
        Q = manning_rect(b, h, n, slope)
        print(f"b={b}, h={h}, n={n}, S={slope} → Q = {Q:.3f} m³/s")
    except ValueError as err:
        print(f"b={b}, h={h}, n={n}, S={slope} → ❌ 輸入錯誤：{err}")

Q = manning_rect(b=3.0, h=1.5, n=0.03, slope=0.001)
print(f"手動測試（正常輸入）：Q = {Q:.3f} m³/s")
